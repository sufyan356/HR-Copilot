from typing import List, Dict, Any, Optional
from typing_extensions import TypedDict


class HRBotState(TypedDict, total=False):

    # ========================================================
    # USER
    # ========================================================

    user_id: Optional[int]

    # ========================================================
    # CURRENT USER QUERY
    # ========================================================

    query: str

    # ========================================================
    # DATABASE CHAT HISTORY
    # ========================================================

    chat_history: str

    # ========================================================
    # RETRIEVAL RESULTS
    # ========================================================

    retrieval_results: List[Dict[str, Any]]

    # ========================================================
    # RETRIEVED CONTEXT
    # ========================================================

    context: str

    # ========================================================
    # FINAL ANSWER
    # ========================================================

    answer: str